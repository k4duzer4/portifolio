const { chromium } = require('C:/Users/kadus/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const fs = require('node:fs/promises')
const output = 'D:/CodexWorkspaces/carlos-franco-orbita-deps/qa'
const origin = process.env.PORTFOLIO_URL || 'http://127.0.0.1:5175'
;(async () => {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
  const errors = [], failed = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('response', response => { if (response.status() >= 400 && response.url().startsWith(origin)) failed.push({ status: response.status(), url: response.url() }) })
  await page.goto(origin, { waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: 'Engenheiro de software.' }).waitFor()
  await page.waitForTimeout(1800)
  await page.screenshot({ path: `${output}/desktop-hero.png` })
  const report = []
  for (const width of [1440, 1024, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.waitForTimeout(180)
    report.push(await page.evaluate(width => ({ width, documentWidth: document.documentElement.scrollWidth, overflow: document.documentElement.scrollWidth > innerWidth + 1, overlapping: [...document.querySelectorAll('main section')].map(x => ({ id: x.id, width: Math.ceil(x.getBoundingClientRect().width) })).filter(x => x.width > innerWidth + 1) }), width))
    if (width === 390) await page.screenshot({ path: `${output}/mobile-hero.png` })
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Pausar animações' }).click()
  if (await page.locator('html').getAttribute('data-motion') !== 'off') throw new Error('Motion pause failed')
  await page.getByRole('button', { name: 'Explorar projeto: GameLog' }).click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('dialog').getByRole('heading', { name: 'GameLog', exact: true }).waitFor()
  await page.screenshot({ path: `${output}/project-dialog.png` })
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  if (!await page.getByRole('button', { name: 'Explorar projeto: GameLog' }).evaluate(el => el === document.activeElement)) throw new Error('Project focus was not restored')
  await page.getByRole('button', { name: 'Experiência com IA', exact: true }).click()
  await page.getByText(/Na Clair & Leitão, participei da integração/).waitFor()
  await page.locator('#laboratorio').screenshot({ path: `${output}/lab-result.png` })
  await page.getByLabel('Pergunte sobre minha experiência, stack ou formação').fill('Informação inexistente xyz')
  await page.getByRole('button', { name: 'Explorar pergunta', exact: true }).click()
  await page.getByText(/Ainda não tenho uma informação específica/).waitFor()
  await page.locator('#projetos').screenshot({ path: `${output}/projects.png` })
  await page.locator('#sobre').screenshot({ path: `${output}/about.png` })
  await page.locator('#contato').screenshot({ path: `${output}/contact.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Abrir navegação' }).click()
  await page.getByRole('navigation', { name: 'Navegação móvel' }).getByRole('link', { name: /Trajetória/ }).click()
  if (await page.getByRole('button', { name: 'Abrir navegação' }).getAttribute('aria-expanded') !== 'false') throw new Error('Mobile menu did not close')
  await page.locator('#contato').screenshot({ path: `${output}/contact-mobile.png` })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(origin + '/curriculo', { waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: 'Carlos Eduardo Amaro de Sousa Franco de Sá' }).waitFor()
  await page.screenshot({ path: `${output}/resume-mobile.png`, fullPage: true })
  const resumeOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)
  await page.goto(origin, { waitUntil: 'networkidle' })
  if (await page.locator('html').getAttribute('data-motion') !== 'off') throw new Error('Reduced motion not honored')
  console.log(JSON.stringify({ errors, failed, report, resumeOverflow, interactions: ['motion pause', 'project dialog', 'Escape dismissal', 'local profile retrieval', 'unknown query fallback', 'mobile navigation', 'resume route', 'reduced motion'] }, null, 2))
  await browser.close()
  if (errors.length || failed.length || report.some(x => x.overflow) || resumeOverflow) process.exitCode = 1
})().catch(error => { console.error(error); process.exit(1) })
