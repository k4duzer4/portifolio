const { chromium } = require('C:/Users/kadus/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  await page.goto(process.env.PORTFOLIO_URL || 'http://127.0.0.1:4173', { waitUntil: 'networkidle' })
  await page.locator('.scene-canvas canvas').waitFor()
  await page.waitForTimeout(1700)
  const scene = page.locator('.scene-canvas')
  const first = await scene.screenshot()
  await page.waitForTimeout(250)
  const second = await scene.screenshot()
  if (first.equals(second)) throw new Error('The scene did not animate')
  await page.getByRole('button', { name: 'Explorar partículas', exact: true }).click()
  await page.waitForTimeout(700)
  if (await page.getByRole('button', { name: 'Explorar superfície', exact: true }).getAttribute('aria-pressed') !== 'true') throw new Error('Particle mode did not activate')
  await page.getByRole('button', { name: 'Pausar animações' }).click()
  await page.waitForTimeout(350)
  const pausedFirst = await scene.screenshot()
  await page.waitForTimeout(300)
  const pausedSecond = await scene.screenshot()
  if (!pausedFirst.equals(pausedSecond)) throw new Error('Scene did not remain paused')
  await page.getByRole('button', { name: 'Ativar animações' }).click()
  await page.waitForTimeout(300)
  const resumed = await scene.screenshot()
  if (pausedSecond.equals(resumed)) throw new Error('Scene did not resume')
  console.log('3D: visible motion, particle mode, exact paused frames and resumed motion verified.')
  await browser.close()
})().catch(error => { console.error(error); process.exit(1) })
